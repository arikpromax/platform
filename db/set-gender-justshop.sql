update public.sites s
   set config = jsonb_set(config, '{collections}', (
     select jsonb_agg(
       case when c->>'key' = 'products' and not (c->'fields' @> '[{"key":"gender"}]'::jsonb)
         then jsonb_set(c, '{fields}', (c->'fields') || jsonb_build_array(jsonb_build_object(
                'key', 'gender', 'name', 'Кому', 'type', 'select', 'extra', true,
                'options', jsonb_build_array(
                  jsonb_build_object('value', '',  'label', 'Без поділу — видно всім'),
                  jsonb_build_object('value', 'm', 'label', 'Чоловіче'),
                  jsonb_build_object('value', 'w', 'label', 'Жіноче')),
                'hint', 'Розділ сайту, у якому показувати річ')))
         else c end)
     from jsonb_array_elements(config->'collections') c))
 where s.slug = 'justshop';

